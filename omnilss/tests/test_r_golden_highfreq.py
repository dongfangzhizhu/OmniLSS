"""P1: high-frequency family golden replay (D2.227).

Golden fixtures: omnilss/tests/fixtures/r_golden/regenerated/<case>.json,
regenerated by generate_golden.R against live R 4.6.0 / gamlss 5.5.0 /
gamlss.dist 6.1.1.  Eleven high-frequency families join the original nine
with a fixed RS-fit golden:
  - D2.227: WEI, LOGNO, EXP, GEOM, IGAMMA, NO2
  - D2.228: LO, RG, PE, NBII, BEINF

Both sides run n.cyc = 100 for the new cases (recorded as n_cyc in the
manifest and in each fixture) so they reach the same optimum: at the default
budget R stops earlier on a near-flat ridge and the coefficient gap for
WEI/GEOM/NO2/IGAMMA exceeded 2e-4 purely from the different stopping point
(deviance still matched to ~1e-8).  Candidates that genuinely diverge even at
n.cyc=100 (TF, SHASH, SN1, ZIP, DEL, SIMPLEX, BCCG, JSUo, GT) were
deliberately not promoted; a flat nu/tau ridge with a different local optimum
is not evidence of density parity.  ZIPF matched on 2/3 seeds only, and R's
installed gamlss.dist 6.1.1 has no rDELAPORT, so both stayed out.
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pytest

from omnilss import gamlss
from omnilss.operations import deviance

GOLDEN_DIR = Path(__file__).parent / "fixtures" / "r_golden" / "regenerated"
MANIFEST = json.loads((GOLDEN_DIR / "manifest.json").read_text(encoding="utf-8"))

CASES = (
    # D2.227 batch 1
    "wei_y_x_seed_20261115",
    "logno_y_x_seed_20261116",
    "exp_y_x_seed_20261117",
    "geom_y_x_seed_20261118",
    "igamma_y_x_seed_20261119",
    "no2_y_x_seed_20261120",
    # D2.228 batch 2
    "lo_y_x_seed_20261121",
    "rg_y_x_seed_20261122",
    "pe_y_x_seed_20261123",
    "nbii_y_x_seed_20261121",
    "beinf_y_x_seed_20261122",
)


@pytest.mark.parametrize("case", CASES)
def test_highfreq_golden_replay(case):
    entry = MANIFEST[case]
    payload = json.loads((GOLDEN_DIR / f"{case}.json").read_text(encoding="utf-8"))
    data = {
        "y": np.asarray(payload["data"]["y"], dtype=float),
        "x": np.asarray(payload["data"]["x"], dtype=float),
    }
    kwargs = {}
    if "n_cyc" in entry:
        kwargs["max_iter"] = int(entry["n_cyc"])
    model = gamlss(payload["formula"], family=entry["family"], data=data, **kwargs)

    expected = payload["expected"]
    for param in ("mu", "sigma", "nu", "tau"):
        key = f"{param}_coefficients"
        if key not in expected:
            continue
        np.testing.assert_allclose(
            np.ravel(np.asarray(model.coefficients[param], dtype=float)),
            np.asarray(expected[key], dtype=float),
            rtol=2e-4,
            atol=2e-4,
            err_msg=f"{case} {param} coefficients",
        )
    np.testing.assert_allclose(
        float(deviance(model)),
        float(expected["deviance"]),
        rtol=2e-4,
        atol=2e-4,
        err_msg=f"{case} deviance",
    )


def test_highfreq_cases_are_in_the_pinned_template():
    template = json.loads(
        (GOLDEN_DIR.parent / "manifest_template.json").read_text(encoding="utf-8")
    )
    for case in CASES:
        assert case in template["cases"], case
        assert template["cases"][case]["kind"] == "fitting"
