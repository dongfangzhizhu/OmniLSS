"""Phase 8.1: L3 service completeness — capability/version/health contract.

The gRPC CapabilityService exposes CapabilityMatrix, RouteCapability, Version
and Health; the Fit/Predict/Sample services cover the full lifecycle.  proto
is the frozen contract; *_pb2.py is regenerated by generate_grpc_stubs.py in
CI (grpcio-tools), so this suite asserts on the proto + server source.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

SRC = Path(__file__).resolve().parents[1] / "src"
sys.path.insert(0, str(SRC))

PROTO = SRC / "omnilss" / "api" / "grpc" / "proto" / "capability.proto"
SERVER = SRC / "omnilss" / "api" / "grpc" / "server.py"


def test_proto_defines_version_and_health():
    """capability.proto freezes Version and Health RPCs + messages."""
    text = PROTO.read_text(encoding="utf-8")
    assert "message VersionRequest {}" in text
    assert "message VersionResponse" in text
    assert "message HealthRequest {}" in text
    assert "message HealthResponse" in text
    assert "rpc Version(VersionRequest) returns (VersionResponse)" in text
    assert "rpc Health(HealthRequest) returns (HealthResponse)" in text


def test_proto_keeps_capability_rpcs():
    """Existing capability RPCs remain part of the frozen contract."""
    text = PROTO.read_text(encoding="utf-8")
    assert "rpc CapabilityMatrix" in text
    assert "rpc RouteCapability" in text


def test_server_implements_version_and_health():
    """The servicer implements Version and Health handlers."""
    text = SERVER.read_text(encoding="utf-8")
    assert "def Version(self, request, context)" in text
    assert "def Health(self, request, context)" in text
    assert "capability_pb2.VersionResponse(" in text
    assert "capability_pb2.HealthResponse(" in text


def test_server_version_reports_x64_and_version():
    """Version handler wires __version__ and x64 precision."""
    text = SERVER.read_text(encoding="utf-8")
    assert "__version__" in text
    assert "jax_enable_x64" in text


def test_server_health_reports_model_count():
    """Health handler uses the registry model count.

    D2.142: the handler reports "degraded" when any artifact fails its audit and
    "ok" otherwise, so the old exact string status="ok" never appears.  The
    contract worth pinning is the conditional plus the registry count.
    """
    text = SERVER.read_text(encoding="utf-8")
    assert "REGISTRY.list_ids()" in text
    assert 'status="degraded" if unhealthy else "ok"' in text


def test_core_services_registered():
    """Fit/Predict/Sample/Capability services are all registered on the server."""
    text = SERVER.read_text(encoding="utf-8")
    for service in (
        "FitServiceServicer",
        "PredictServiceServicer",
        "SampleServiceServicer",
        "CapabilityServiceServicer",
    ):
        assert f"add_{service}_to_server" in text, f"{service} not registered"
