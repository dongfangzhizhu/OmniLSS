#: Resolved family objects, cached per process.  resolve_family *constructs* a
#: fresh object on every call, and for an AD family that re-runs
#: build_ad_family's JIT warm-up (~20-40 s).
_FAMILY_CACHE: dict[str, object] = {}


def _family(name: str):
    if name not in _FAMILY_CACHE:
        _FAMILY_CACHE[name] = resolve_family(name)
    return _FAMILY_CACHE[name]


def _sample(family: str) -> dict[str, list[float]]:
    return SAMPLES[family]


def _eval_r_expression(expr: str, y: np.ndarray) -> np.ndarray | float:
    """Evaluate one of R's initial expressions on the same sample."""
    if RSCRIPT is None:  # pragma: no cover - CI without R
        pytest.skip("Rscript not on PATH")
    y_vec = "c(" + ", ".join(repr(float(v)) for v in y) + ")"
    # Bind y once and evaluate R's expression in that scope.  A textual
    # .replace("y", <vector>, 1) is wrong for every expression that names y
    # more than once -- "(log(y)+mean(log(y)))/2" left the second y dangling
    # and R raised "object 'y' not found".
    code = "cat(format(with(list(y = " + y_vec + "), " + expr + "), digits = 17))"
    proc = subprocess.run([RSCRIPT, "-e", code], capture_output=True,
                          text=True, timeout=300)
    assert proc.returncode == 0, f"R failed: {proc.stderr[-300:]}"
    out = proc.stdout.strip()
    if out.startswith("c(") or " " in out:
        return np.asarray([float(v) for v in out.replace("c(", "").replace(")", "").split()])
    return float(out)


@pytest.mark.skipif(RSCRIPT is None, reason="Rscript not on PATH")
class TestInitialValuesAgainstR:
    @pytest.mark.parametrize("family", sorted(R_INITIALS))
    def test_sigma_initial_is_not_on_the_floor(self, family):
        """The regression guard: sigma must not start at eps."""
        payload = _sample(family)
        y = np.asarray(payload["y"], dtype=float)
        w = np.ones_like(y)
        fam = _family(family)
        mu0 = _initial_mu_target(fam, y, w)
        sigma0 = float(np.ravel(_initial_sigma(fam, y, mu0, w))[0])
        assert sigma0 > 1e-12, (
            family + " starts sigma at " + repr(sigma0) + " -- the eps-floor "
            "signature (D2.59)"
        )

    @pytest.mark.parametrize("family", sorted(R_INITIALS))
    def test_sigma_initial_matches_r_expression(self, family):
        spec = R_INITIALS[family]
        payload = _sample(family)
        y = np.asarray(payload["y"], dtype=float)
        w = np.ones_like(y)
        fam = _family(family)
        mu0 = _initial_mu_target(fam, y, w)
        sigma0 = float(np.ravel(_initial_sigma(fam, y, mu0, w))[0])
        ref = _eval_r_expression(spec["sigma"], y)
        ref_val = float(np.ravel(np.asarray(ref))[0])
        np.testing.assert_allclose(sigma0, ref_val, rtol=1e-12,
                                   err_msg=family + " sigma.initial")

    @pytest.mark.parametrize("family", sorted(R_INITIALS))
    def test_mu_initial_matches_r_expression(self, family):
        spec = R_INITIALS[family]
        payload = _sample(family)
        y = np.asarray(payload["y"], dtype=float)
        w = np.ones_like(y)
        fam = _family(family)
        ours = np.asarray(_initial_mu_target(fam, y, w)).ravel()
        ref = np.asarray(_eval_r_expression(spec["mu"], y), dtype=float).ravel()
        np.testing.assert_allclose(ours, ref, rtol=1e-12,
                                   err_msg=family + " mu.initial")

    @pytest.mark.parametrize("family", sorted(R_INITIALS))
    def test_extra_parameter_initials_match_r(self, family):
        spec = R_INITIALS[family]
        payload = _sample(family)
        y = np.asarray(payload["y"], dtype=float)
        w = np.ones_like(y)
        fam = _family(family)
        mu0 = _initial_mu_target(fam, y, w)
        for name, expected in spec["extras"].items():
            ours = float(np.ravel(np.asarray(
                _initial_parameter_value(fam, name, y, mu0, w), dtype=float))[0])
            if isinstance(expected, str):
                ref = float(np.ravel(np.asarray(
                    _eval_r_expression(expected, y)))[0])
            else:
                ref = float(expected)
            np.testing.assert_allclose(ours, ref, rtol=1e-12,
                                       err_msg=family + " " + name + ".initial")
